import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const manifest = JSON.parse(read('contracts/production-circulation.v1.json'));
const registryDirectory = read('process/continuum/powerfarm/registry.py');
const writerMigration = read('process/migrations/20260830130000_process_admission_writer.sql');
const cardOnlyMigration = read('process/migrations/20260830140000_process_card_only_admission.sql');
const writerClient = read('process/continuum/powerfarm/runtime/postgrest_writer.py');
const processWorker = read('process/worker/src/core.mjs');
const heartimeToken = read('heartime/worker/src/token-provider.mjs');
const heartimeState = read('heartime/worker/src/postgrest-state.mjs');
const traceMigration = read('heartime/migrations/20260830074000_heartime_operational_projections.sql');
const traceSource = read('circulation/lib/trace.mjs');
const checks = [];
const check = (label, condition) => { assert.equal(Boolean(condition), true, label); checks.push(label); };

check('production circulation contract id is pinned', manifest.contract_id === 'pf.contract.production-circulation.v1');
check('Registry directory wire version is pinned', manifest.registry_directory === 'powerfarm.registry.directory.v1');
check('Registry runtime-token wire version is pinned', manifest.registry_runtime_token === 'powerfarm.registry.runtime-token.v1');
check('Process admission Service Binding wire version is pinned', manifest.process_admission_port === 'powerfarm.process.admission-port.v1');
check('Process Card-bound write wire version is pinned', manifest.process_admission_write === 'powerfarm.process.admission-write.v2');
check('PostgREST RegistryDirectory exists', /class PostgrestRegistryDirectory/.test(registryDirectory));
check('RegistryDirectory is read-only HTTP RPC', /powerfarm_registry_office_snapshot_v1/.test(registryDirectory) && /powerfarm_registry_key_binding_v1/.test(registryDirectory));
check('RegistryDirectory production transport requires HTTPS', /must use HTTPS outside explicit local development/.test(registryDirectory));
check('Process PostgreSQL writer requires dedicated runtime identity', /pf\.runtime\.process-writer/.test(writerMigration));
check('Process writer serializes each timeline transactionally', /pg_advisory_xact_lock/.test(writerMigration));
check('Process writer rejects stale heads and chain breaks', /admission_stale_head/.test(writerMigration) && /admission_chain_break/.test(writerMigration));
check('Process writer preserves external pf refs', /actor_external_ref/.test(writerMigration) && /office_external_ref/.test(writerMigration));
check('authenticated Process persistence is Card-bound', /admit_card_batch_v2/.test(cardOnlyMigration) && /execution_slice_sha256/.test(cardOnlyMigration));
check('legacy Process writer is revoked from authenticated', /revoke all on function continuum\.admit_batch_v1\(jsonb\) from authenticated/.test(cardOnlyMigration));
check('authenticated callers do not receive direct continuum acts insert', !/grant insert on continuum\.acts to authenticated/i.test(writerMigration));
check('Python production writer selects continuum schema', /content-profile/.test(writerClient) && /accept-profile/.test(writerClient));
check('Process Service Binding obtains Registry runtime credential', /REGISTRY_IDENTITY\.issueRuntimeToken/.test(processWorker));
check('Process Service Binding uses no service-role key', !/service[_-]?role/i.test(processWorker));
check('Process Service Binding propagates operational trace headers', /traceHeaders/.test(processWorker));
check('Heartime gets its credential from Registry binding', /REGISTRY_IDENTITY/.test(heartimeToken) && /RegistryRuntimeTokenProvider/.test(heartimeToken));
check('Heartime PostgREST retries one expired runtime token', /response\.status === 401/.test(heartimeState) && /forceRefresh: true/.test(heartimeState));
check('Heartime persists compact trace events', /record_trace_event_v1/.test(heartimeState) && /heartime\.trace_events/.test(traceMigration));
check('Heartime trace table forbids sensitive body keys', /chain_of_thought/.test(traceMigration) && /card_body/.test(traceMigration));
check('W3C traceparent is deterministic from PowerFarm refs', /w3cTraceparent/.test(traceSource) && /powerfarm-trace-v1/.test(traceSource));
check('production writer tests exist', fs.existsSync(path.join(root, 'process/worker/tests/process-writer.test.mjs')));
check('production circulation golden exists', fs.existsSync(path.join(root, 'conformance/circulation/production-circulation.integration.test.mjs')));
check('production circulation golden fixture is pinned', fs.existsSync(path.join(root, 'conformance/circulation/golden/production-circulation.golden.json')));

console.log(`PRODUCTION CIRCULATION CONTRACT: PASS · ${checks.length} checks`);
for (const label of checks) console.log(`  ok    ${label}`);
