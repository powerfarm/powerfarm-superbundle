import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');
const exists = (relative) => fs.existsSync(path.join(root, relative));
const sha = (relative) => createHash('sha256').update(fs.readFileSync(path.join(root, relative))).digest('hex');
const manifest = JSON.parse(read('contracts/legacy-removal.v1.json'));
const kernel = read('process/continuum/powerfarm/kernel.py');
const aiIdentity = read('process/continuum-ai-sdk/src/identity.mjs');
const aiWrapper = read('process/continuum-ai-sdk/src/wrap-tools.mjs');
const adkPlugin = read('process/continuum-adk/src/continuum_adk/plugin.py');
const adkPublic = read('process/continuum-adk/src/continuum_adk/__init__.py');
const attentionContract = read('circulation/attention/lib/contract.mjs');
const attentionController = read('circulation/attention/lib/controller.mjs');
const cardOnlySql = read('process/migrations/20260830140000_process_card_only_admission.sql').toLowerCase();
const processWorker = read('process/worker/src/core.mjs');
const checks = [];
const check = (label, condition) => { assert.equal(Boolean(condition), true, label); checks.push(label); };

check('legacy-removal contract id is pinned', manifest.contract_id === 'pf.contract.legacy-removal.v1');
check('Card carrier version remains v1', manifest.card_contract === 'powerfarm.card.v1');
check('ExecutionSlice version is v4', manifest.execution_slice === 'powerfarm.execution-slice.v4');
check('Card-bound Process write version is v2', manifest.process_admission_write === 'powerfarm.process.admission-write.v2');
check('writable Continuum requires Registry by default', /writable Continuum Kernel requires a RegistryDirectory/.test(kernel));
check('embedded identity is explicit test-only mode', /identity_mode='embedded-test' explicitly/.test(kernel));
check('Registry identity mode requires RegistryDirectory', /identity_mode='registry' requires a RegistryDirectory/.test(kernel));
check('AI SDK resolver requires ExecutionSlice', /sealed ExecutionSlice is required/.test(aiIdentity));
check('AI SDK wrapper derives refs from ExecutionSlice', /executionRefsFromSlice\(identity\.executionSlice\)/.test(aiWrapper));
check('AI SDK has no legacy callRefs source', !exists('process/continuum-ai-sdk/src/call-refs.mjs'));
check('AI SDK has no callRefs golden', !exists('process/continuum-ai-sdk/tests/golden/call-refs.test.mjs'));
check('AI SDK local Python transport is test support only', !exists('process/continuum-ai-sdk/src/python-port.mjs') && !exists('process/continuum-ai-sdk/python/bridge.py'));
check('AI SDK public entrypoint exports no bootstrap-capable Python port', !/PythonContinuumPort/.test(read('process/continuum-ai-sdk/src/index.mjs')));
check('ADK plugin requires ExecutionSlice resolver', /ContinuumPlugin requires an ExecutionSlice resolver/.test(adkPlugin));
check('ADK plugin derives refs from ExecutionSlice', /execution_refs_from_slice/.test(adkPlugin));
check('public ADK bootstrap module is removed', !exists('process/continuum-adk/src/continuum_adk/bootstrap.py'));
check('public ADK API does not export office bootstrap', !/create_office|assign_occupancy|provision_office|Grant/.test(adkPublic));
check('First Seam requires canonical Card source', /Cards\.listCurrent must return sealed/.test(attentionContract));
check('First Seam uses canonical source validator', /normalizeCirculatingCard/.test(attentionController));
check('WakePack validates source content binding', /WakePack source binding mismatch/.test(attentionController));
check('Card-only binding table is durable', /create table continuum\.card_admission_bindings/.test(cardOnlySql));
check('Card-bound writer requires execution slice digest', /execution_slice_sha256/.test(cardOnlySql));
check('legacy writer execute is revoked from authenticated', /revoke all on function continuum\.admit_batch_v1\(jsonb\) from authenticated/.test(cardOnlySql));
check('Card-bound writer is granted to authenticated', /grant execute on function continuum\.admit_card_batch_v2\(jsonb\) to authenticated/.test(cardOnlySql));
check('legacy writer is not re-granted in final migration', !/grant execute on function continuum\.admit_batch_v1\(jsonb\) to authenticated/.test(cardOnlySql));
check('Process Service Binding calls only Card-bound writer', /rpc: 'admit_card_batch_v2'/.test(processWorker) && !/rpc: 'admit_batch_v1'/.test(processWorker));
check('Process Service Binding requires outer Card ref', /assertInstitutionalRef\(request\.card_ref/.test(processWorker));
check('Process Service Binding requires beat ref', /assertInstitutionalRef\(request\.beat_ref/.test(processWorker));
check('Process Service Binding requires attempt ref', /assertInstitutionalRef\(request\.attempt_ref/.test(processWorker));
check('Process Service Binding requires ExecutionSlice digest', /execution_slice_sha256 is required/.test(processWorker));
check('Card v1 contract JSON retains M5/M6 hash', sha('contracts/card.v1.json') === '32f555db873bb1f8d0ff76decf8f1233364692292c30a8d3123fea07e43b75fb');
check('Card v1 implementation retains M5/M6 hash', sha('circulation/cards/lib/card-v1.mjs') === '55d734b4f362a9bd9d01b819725af8fb45dca68dfd9f894d661aaa9083123ebc');

console.log(`LEGACY REMOVAL CONTRACT: PASS · ${checks.length} checks`);
for (const label of checks) console.log(`  ok    ${label}`);
